 await etat('bientot',()=>{__DB.tentatives=__DB.tentatives.filter(t=>t.id!=='tz');const n=Date.now(),q=__DB.quiz.find(x=>x.id==='qH');q.date_debut=new Date(n+3*24*H).toISOString();q.date_fin=new Date(n+3*24*H+2*H).toISOString()})
